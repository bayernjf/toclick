// 敏感词本地过滤（双保险，多个人设共用）
export const BANNED_WORDS = [
  "废物",
  "垃圾",
  "没用",
  "蠢货",
  "傻子",
  "白痴",
  "弱智",
  "自杀",
  "去死",
  "肥猪",
  "矮子",
  "穷逼",
  "贱人",
  "婊",
];

// 检查输出是否含敏感词
export function containsBannedWord(text: string): boolean {
  return BANNED_WORDS.some((w) => text.includes(w));
}
